function getTitleById(id) {
  return TITLES.find((t) => t.id === id) || null;
}

function getTitleBySlug(slug) {
  return TITLES.find((t) => t.slug === slug) || null;
}

function getTitlesByType(type) {
  return TITLES.filter((t) => t.type === type);
}

function getFeatured() {
  return TITLES.filter((t) => t.featured);
}

function getTrending() {
  return TITLES.filter((t) => t.trending).sort((a, b) => b.popularity - a.popularity);
}

function getPopular(limit = 20) {
  return [...TITLES].sort((a, b) => b.popularity - a.popularity).slice(0, limit);
}

function getTopRated(limit = 20) {
  return [...TITLES].sort((a, b) => b.rating - a.rating).slice(0, limit);
}

function getLatest(limit = 20) {
  return [...TITLES].sort((a, b) => new Date(b.releaseDate) - new Date(a.releaseDate)).slice(0, limit);
}

function getByGenre(genreId) {
  return TITLES.filter((t) => t.genres.includes(genreId));
}

function searchTitles(query) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  return TITLES.filter(
    (t) =>
      t.title.toLowerCase().includes(q) ||
      t.director.toLowerCase().includes(q) ||
      t.cast.some((c) => c.toLowerCase().includes(q)) ||
      t.genres.some((g) => g.includes(q)) ||
      (t.synopsis && t.synopsis.toLowerCase().includes(q))
  );
}

function filterTitles(options = {}) {
  let results = [...TITLES];

  if (options.type && options.type !== "all") {
    results = results.filter((t) => t.type === options.type);
  }
  if (options.genre && options.genre !== "all") {
    results = results.filter((t) => t.genres.includes(options.genre));
  }
  if (options.year) {
    results = results.filter((t) => t.year === Number(options.year));
  }
  if (options.minRating) {
    results = results.filter((t) => t.rating >= Number(options.minRating));
  }
  if (options.query) {
    const q = options.query.toLowerCase().trim();
    results = results.filter(
      (t) =>
        t.title.toLowerCase().includes(q) ||
        t.director.toLowerCase().includes(q) ||
        t.cast.some((c) => c.toLowerCase().includes(q))
    );
  }

  const sort = options.sort || "popularity";
  switch (sort) {
    case "newest":
      results.sort((a, b) => new Date(b.releaseDate) - new Date(a.releaseDate));
      break;
    case "rating":
      results.sort((a, b) => b.rating - a.rating);
      break;
    case "title":
      results.sort((a, b) => a.title.localeCompare(b.title));
      break;
    case "popularity":
    default:
      results.sort((a, b) => b.popularity - a.popularity);
      break;
  }

  return results;
}

function getCollectionBySlug(slug) {
  return COLLECTIONS.find((c) => c.slug === slug) || null;
}

function getPersonById(id) {
  return PEOPLE.find((p) => p.id === id) || null;
}

function getSimilar(title, limit = 8) {
  if (!title) return [];
  return TITLES.filter(
    (t) =>
      t.id !== title.id &&
      (t.genres.some((g) => title.genres.includes(g)) || t.director === title.director)
  )
    .sort((a, b) => b.popularity - a.popularity)
    .slice(0, limit);
}


