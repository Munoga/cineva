function hashId(id) {
  var h = 0;
  for (var i = 0; i < String(id).length; i++) h = ((h << 5) - h) + String(id).charCodeAt(i) | 0;
  return Math.abs(h);
}

function posterUrl(id, title) {
  return POSTER_IMAGES[hashId(id) % POSTER_IMAGES.length];
}

function backdropUrl(id, title) {
  return BACKDROP_IMAGES[hashId(String(id) + "bg") % BACKDROP_IMAGES.length];
}

