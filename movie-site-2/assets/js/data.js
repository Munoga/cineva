/* Merge admin-added movies from localStorage so they appear like built-in catalogue */
(function mergeAdminMoviesIntoTitles() {
  try {
    var raw = localStorage.getItem("cineva_admin_movies");
    if (!raw) return;
    var extra = JSON.parse(raw);
    if (!Array.isArray(extra) || !extra.length) return;
    extra.forEach(function (m) {
      if (!m || !m.id) return;
      var exists = TITLES.some(function (t) { return t.id === m.id; });
      if (!exists) TITLES.push(m);
    });
  } catch (e) { /* ignore */ }
})();

